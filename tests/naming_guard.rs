//! Shared code must not name a planner (spec §7.12). Shared code is every Rust
//! file outside `src/planners/` plus the hand-written JS. A registered
//! planner's id, Rust type name or folder name fails this test there, string
//! literals included and comments excluded. Files still waiting for a later
//! milestone are listed in `ALLOWLIST` with the milestone that clears them.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use mafis::planning::registry;

/// (file, milestone that removes its last planner name). Spec §7.12: empty by
/// the end of M6.
const ALLOWLIST: &[(&str, &str)] = &[
    ("cli/src/commands/fault.rs", "M6"),
    ("cli/src/commands/fun.rs", "M6"),
    ("cli/src/commands/solver.rs", "M6"),
    ("src/experiment/suite.rs", "M6"),
    ("src/ui/controls.rs", "M4"),
    ("tests/benchmarks.rs", "M6"),
    ("tests/clean_benchmark_validation.rs", "M6"),
    ("tests/planner_expectations.rs", "M6"),
];

const MILESTONES: [&str; 4] = ["M3", "M4", "M5", "M6"];

/// Hand-written JS; `web/mafis.js` is generated by wasm-bindgen.
const JS_FILES: [&str; 3] = ["web/app.js", "web/experiment-worker.js", "web/mapmaker.js"];

/// Rust directories scanned, minus `PLANNER_DIR`.
const RUST_DIRS: [&str; 3] = ["src", "cli/src", "tests"];

const PLANNER_DIR: &str = "src/planners/";

#[derive(Clone, Copy)]
enum Lang {
    Rust,
    Js,
}

/// `source` with every comment removed and every string literal kept. Line
/// breaks inside comments stay, so line numbers still match the file.
fn strip_comments(source: &str, lang: Lang) -> String {
    let chars: Vec<char> = source.chars().collect();
    let mut out = String::with_capacity(source.len());
    let mut i = 0;
    while i < chars.len() {
        let c = chars[i];
        let next = chars.get(i + 1).copied();
        if c == '/' && next == Some('/') {
            while i < chars.len() && chars[i] != '\n' {
                i += 1;
            }
        } else if c == '/' && next == Some('*') {
            // Rust block comments nest; JS ones end at the first `*/`.
            let nests = matches!(lang, Lang::Rust);
            let mut depth = 1;
            i += 2;
            while i < chars.len() && depth > 0 {
                if nests && chars[i] == '/' && chars.get(i + 1) == Some(&'*') {
                    depth += 1;
                    i += 2;
                } else if chars[i] == '*' && chars.get(i + 1) == Some(&'/') {
                    depth -= 1;
                    i += 2;
                } else {
                    if chars[i] == '\n' {
                        out.push('\n');
                    }
                    i += 1;
                }
            }
        } else if c == '"' || (matches!(lang, Lang::Js) && (c == '\'' || c == '`')) {
            i = copy_quoted(&chars, i, &mut out);
        } else if c == '\'' {
            // Rust: a char literal (`'x'`, `'\n'`) or a lifetime (`'a`).
            if next == Some('\\') {
                i = copy_quoted(&chars, i, &mut out);
            } else if chars.get(i + 2) == Some(&'\'') {
                out.extend(&chars[i..i + 3]);
                i += 3;
            } else {
                out.push(c);
                i += 1;
            }
        } else if matches!(lang, Lang::Rust) && raw_string_hashes(&chars, i).is_some() {
            i = copy_raw(&chars, i, &mut out);
        } else {
            out.push(c);
            i += 1;
        }
    }
    out
}

/// Copies the literal opened by the quote at `start`, escapes included;
/// returns the index after its closing quote.
fn copy_quoted(chars: &[char], start: usize, out: &mut String) -> usize {
    let quote = chars[start];
    out.push(quote);
    let mut i = start + 1;
    while i < chars.len() {
        out.push(chars[i]);
        if chars[i] == '\\' {
            if let Some(&escaped) = chars.get(i + 1) {
                out.push(escaped);
            }
            i += 2;
            continue;
        }
        i += 1;
        if chars[i - 1] == quote {
            break;
        }
    }
    i
}

/// The number of `#` in a raw string starting at `i` (`r"`, `r#"`, `br"`…);
/// `None` when no raw string starts there.
fn raw_string_hashes(chars: &[char], i: usize) -> Option<usize> {
    let ident = |c: char| c.is_alphanumeric() || c == '_';
    let starts_token = match i.checked_sub(1).map(|p| chars[p]) {
        None => true,
        Some('b') => i < 2 || !ident(chars[i - 2]),
        Some(prev) => !ident(prev),
    };
    if chars[i] != 'r' || !starts_token {
        return None;
    }
    let hashes = chars[i + 1..].iter().take_while(|&&c| c == '#').count();
    (chars.get(i + 1 + hashes) == Some(&'"')).then_some(hashes)
}

/// Copies the raw string starting at `i`; returns the index after it.
fn copy_raw(chars: &[char], i: usize, out: &mut String) -> usize {
    let hashes = raw_string_hashes(chars, i).expect("a raw string starts here");
    let body = i + hashes + 2;
    out.extend(&chars[i..body]);
    let mut j = body;
    while j < chars.len() {
        if chars[j] == '"'
            && chars[j + 1..].iter().take(hashes).filter(|&&c| c == '#').count() == hashes
        {
            out.extend(&chars[j..j + 1 + hashes]);
            return j + 1 + hashes;
        }
        out.push(chars[j]);
        j += 1;
    }
    j
}

/// Lowercase letters and digits only, so `token_passing`, `TokenPassing` and
/// `"Token Passing"` all compare equal.
fn normalize(text: &str) -> String {
    text.chars().filter(|c| c.is_ascii_alphanumeric()).map(|c| c.to_ascii_lowercase()).collect()
}

/// Each registered planner's id, Rust type name and folder, normalized.
fn tokens() -> BTreeSet<String> {
    let mut tokens = BTreeSet::new();
    for entry in registry::entries() {
        let path = (entry.type_name)();
        tokens.insert(normalize(entry.info.id));
        tokens.extend(path.rsplit("::").next().map(normalize));
        let folder = path.split_once("::planners::").and_then(|(_, rest)| rest.split("::").next());
        tokens.extend(folder.map(normalize));
    }
    tokens
}

/// Every file the guard reads, relative to `root`, with its language.
fn scanned_files(root: &Path) -> Vec<(String, Lang)> {
    fn walk(dir: &Path, found: &mut Vec<PathBuf>) {
        let mut entries: Vec<PathBuf> = std::fs::read_dir(dir)
            .unwrap_or_else(|e| panic!("read {}: {e}", dir.display()))
            .map(|entry| entry.expect("directory entry").path())
            .collect();
        entries.sort();
        for path in entries {
            if path.is_dir() {
                walk(&path, found);
            } else if path.extension().is_some_and(|ext| ext == "rs") {
                found.push(path);
            }
        }
    }
    let mut files = Vec::new();
    for dir in RUST_DIRS {
        let mut found = Vec::new();
        walk(&root.join(dir), &mut found);
        for path in found {
            let rel =
                path.strip_prefix(root).expect("under root").to_string_lossy().replace('\\', "/");
            if !rel.starts_with(PLANNER_DIR) {
                files.push((rel, Lang::Rust));
            }
        }
    }
    files.extend(JS_FILES.iter().map(|&js| (js.to_string(), Lang::Js)));
    files
}

/// Every failure: planner names outside the allowlist, stale allowlist
/// entries, and allowlist milestones outside the plan.
fn check(root: &Path, tokens: &BTreeSet<String>) -> Vec<String> {
    let mut failures = Vec::new();
    for (path, milestone) in ALLOWLIST {
        if !MILESTONES.contains(milestone) {
            failures.push(format!("{path}: milestone {milestone} is not one of {MILESTONES:?}"));
        }
    }
    let files = scanned_files(root);
    for (path, _) in ALLOWLIST {
        if !files.iter().any(|(file, _)| file == path) {
            failures.push(format!("{path}: not a scanned file; remove it from ALLOWLIST"));
        }
    }
    for (rel, lang) in &files {
        let rel = rel.as_str();
        let source =
            std::fs::read_to_string(root.join(rel)).unwrap_or_else(|e| panic!("read {rel}: {e}"));
        let hits: Vec<String> = strip_comments(&source, *lang)
            .lines()
            .enumerate()
            .flat_map(|(n, line)| {
                let line = normalize(line);
                tokens
                    .iter()
                    .filter(move |token| line.contains(token.as_str()))
                    .map(move |token| format!("{rel}:{}: {token}", n + 1))
            })
            .collect();
        let allowed = ALLOWLIST.iter().any(|(path, _)| *path == rel);
        match (hits.is_empty(), allowed) {
            (false, false) => failures.extend(hits),
            (true, true) => {
                failures.push(format!("{rel}: no planner name left; remove it from ALLOWLIST"))
            }
            _ => {}
        }
    }
    failures
}

#[test]
fn rust_strip_keeps_strings_drops_comments() {
    let src = "let a = \"kept // not a comment\"; // dropped\n\
               let b = 1; /* dropped /* nested */ still dropped */ let c = 2;\n";
    let out = strip_comments(src, Lang::Rust);
    assert!(out.contains("\"kept // not a comment\""), "{out}");
    assert!(!out.contains("dropped"), "{out}");
    assert!(out.contains("let c = 2;"), "{out}");
    assert_eq!(out.lines().count(), src.lines().count());
}

#[test]
fn rust_strip_handles_raw_strings_and_lifetimes() {
    let src = "fn f<'a>(x: &'a str) -> char { let r = r#\"raw \"// kept\" \"#; let q = '\\''; '/' } // gone\n";
    let out = strip_comments(src, Lang::Rust);
    assert!(out.contains("r#\"raw \"// kept\" \"#"), "{out}");
    assert!(out.contains("'\\''") && out.contains("'/' }"), "{out}");
    assert!(!out.contains("gone"), "{out}");
}

#[test]
fn js_strip_keeps_all_string_kinds() {
    let src = "const a = 'x // y'; const b = \"p /* q */\"; const c = `t // u`; // gone\n\
               /* gone\ntoo */ const d = 1;\n";
    let out = strip_comments(src, Lang::Js);
    assert!(
        out.contains("'x // y'") && out.contains("\"p /* q */\"") && out.contains("`t // u`"),
        "{out}"
    );
    assert!(!out.contains("gone") && !out.contains("too"), "{out}");
    assert!(out.contains("const d = 1;"), "{out}");
    assert_eq!(out.lines().count(), src.lines().count());
}

#[test]
fn tokens_cover_id_type_and_folder() {
    let tokens = tokens();
    for entry in registry::entries() {
        let path = (entry.type_name)();
        let (_, inside) = path.split_once("::planners::").expect("planners live in src/planners/");
        let folder = inside.split("::").next().expect("a planner folder");
        let type_name = path.rsplit("::").next().expect("a type name");
        for name in [entry.info.id, folder, type_name] {
            assert!(tokens.contains(&normalize(name)), "{name} missing from {tokens:?}");
        }
    }
}

#[test]
fn shared_code_names_no_planner() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let failures = check(root, &tokens());
    assert!(
        failures.is_empty(),
        "shared code names a planner (spec §7.12):\n{}",
        failures.join("\n")
    );
}
